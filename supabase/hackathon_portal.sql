-- One row per (team, layer): keeps the stack generic instead of fixed columns.
create table if not exists public.hackathon_team_stack (
  team_id uuid not null references public.hackathon_teams(id) on delete cascade,
  layer text not null,
  option_id int not null references public.hackathon_tech_options(id) on delete cascade,
  primary key (team_id, layer)
);

create table if not exists public.hackathon_participants (
  id uuid primary key default gen_random_uuid(),
  hackathon_id uuid not null references public.hackathons(id) on delete cascade,
  team_id uuid not null references public.hackathon_teams(id) on delete cascade,
  role text not null check (role in ('leader', 'member')),
  full_name text not null,
  registration_number text not null,
  year_of_study smallint not null check (year_of_study between 1 and 5),
  phone text not null check (phone ~ '^[6-9][0-9]{9}$'),
  department text not null,
  college text not null,
  created_at timestamptz not null default now(),
  check (char_length(full_name) <= 100 and char_length(registration_number) <= 30
     and char_length(department) <= 100 and char_length(college) <= 150)
);
create unique index if not exists hackathon_participants_one_leader
  on public.hackathon_participants (team_id) where role = 'leader';
-- one registration number per college per hackathon
create unique index if not exists hackathon_participants_reg_college
  on public.hackathon_participants (hackathon_id, upper(registration_number), lower(college));
create index if not exists hackathon_participants_team_idx
  on public.hackathon_participants (team_id);

-- Flat view for the admin table and CSV export (RLS applies to the caller).
-- `stack` is a {layer: option name} object so the view works for any layers.
create or replace view public.hackathon_roster with (security_invoker = true) as
select t.hackathon_id, t.id as team_id, t.code as team_code, t.name as team_name,
       p.id as participant_id, p.role, p.full_name, p.registration_number,
       p.year_of_study, p.phone, p.department, p.college,
       coalesce((select jsonb_object_agg(s.layer, o.name)
                   from public.hackathon_team_stack s
                   join public.hackathon_tech_options o on o.id = s.option_id
                  where s.team_id = t.id), '{}'::jsonb) as stack,
       t.problem_id, ps.title as problem_statement, ps.gist as problem_gist,
       t.assigned_at, t.created_at as registered_at, t.problem_changes, t.stack_rerolls
from public.hackathon_teams t
join public.hackathon_participants p on p.team_id = t.id
left join public.hackathon_problems ps on ps.id = t.problem_id
order by t.code, (p.role = 'leader') desc, p.created_at;

-- =====================================================================
-- 2) Admin check (core_team, same rule the site uses everywhere)
-- =====================================================================
-- profiles.role may be an enum, hence the ::text cast. Named hackathon_is_admin
-- so it can never clash with (or overwrite) a function elsewhere in the project.

create or replace function public.hackathon_is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role::text = 'core_team'
  );
$$;

