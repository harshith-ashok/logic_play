-- Public: does this hackathon exist, is it open, which team sizes apply.
-- Returns null for an unknown slug. Deliberately omits the WhatsApp link.
create or replace function public.hackathon_registration_status(p_slug text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'name', h.name,
    'description', h.description,
    'open', h.registration_open
            and (select count(*) from public.hackathon_teams t where t.hackathon_id = h.id) < h.max_teams,
    'min_team_size', h.min_team_size,
    'max_team_size', h.max_team_size)
  from public.hackathons h where h.slug = p_slug;
$$;

-- Public: creates team + leader + members in one transaction, returns the code.
create or replace function public.hackathon_register_team(
  p_slug text, p_team_name text, p_leader jsonb, p_members jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  cfg public.hackathons;
  v_hid uuid;
  v_name text := btrim(coalesce(p_team_name, ''));
  v_members jsonb := coalesce(p_members, '[]'::jsonb);
  v_all jsonb;
  v_size int;
  v_team_id uuid;
  v_code text;
  v_tries int := 0;
  p jsonb;
  v_i int;
  v_who text;
  v_phone text;
  v_year int;
begin
  select id into v_hid from public.hackathons where slug = p_slug;
  if v_hid is null then raise exception 'Hackathon not found.'; end if;

  -- one registration/draw at a time per hackathon: safe cap + unique codes
  perform pg_advisory_xact_lock(727001, hashtext(v_hid::text));

  select * into cfg from public.hackathons where id = v_hid;
  if not cfg.registration_open then raise exception 'Registration is closed.'; end if;
  if (select count(*) from public.hackathon_teams where hackathon_id = v_hid) >= cfg.max_teams then
    raise exception 'Registration is full.';
  end if;

  if char_length(v_name) < 2 or char_length(v_name) > 50 then
    raise exception 'Team name must be 2 to 50 characters.';
  end if;
  if jsonb_typeof(p_leader) is distinct from 'object' then
    raise exception 'Leader details are required.';
  end if;
  if jsonb_typeof(v_members) <> 'array' then
    raise exception 'Members must be a list.';
  end if;

  v_size := 1 + jsonb_array_length(v_members);
  if v_size < cfg.min_team_size or v_size > cfg.max_team_size then
    raise exception 'A team needs % to % people including the leader.',
      cfg.min_team_size, cfg.max_team_size;
  end if;

  if exists (select 1 from public.hackathon_teams
              where hackathon_id = v_hid and lower(name) = lower(v_name)) then
    raise exception 'Team name "%" is already taken.', v_name;
  end if;

  -- unique random 3-digit code (100-999) within this hackathon
  loop
    v_code := (100 + floor(random() * 900))::int::text;
    exit when not exists (select 1 from public.hackathon_teams
                           where hackathon_id = v_hid and code = v_code);
    v_tries := v_tries + 1;
    if v_tries > 200 then raise exception 'Could not generate a team code. Try again.'; end if;
  end loop;

  insert into public.hackathon_teams (hackathon_id, code, name)
  values (v_hid, v_code, v_name) returning id into v_team_id;

  v_all := jsonb_build_array(p_leader) || v_members;

  for p, v_i in
    select e.value, e.ord::int from jsonb_array_elements(v_all) with ordinality as e(value, ord)
  loop
    v_who := coalesce(nullif(btrim(p->>'full_name'), ''), 'person ' || v_i);

    if nullif(btrim(p->>'full_name'), '') is null
       or nullif(btrim(p->>'registration_number'), '') is null
       or nullif(btrim(p->>'department'), '') is null
       or nullif(btrim(p->>'college'), '') is null then
      raise exception 'All fields are required for %.', v_who;
    end if;

    if char_length(btrim(p->>'full_name')) > 100
       or char_length(btrim(p->>'registration_number')) > 30
       or char_length(btrim(p->>'department')) > 100
       or char_length(btrim(p->>'college')) > 150 then
      raise exception 'One of the fields is too long for %.', v_who;
    end if;

    v_phone := regexp_replace(coalesce(p->>'phone', ''), '\D', '', 'g');
    if length(v_phone) = 12 and left(v_phone, 2) = '91' then v_phone := substr(v_phone, 3); end if;
    if v_phone !~ '^[6-9][0-9]{9}$' then
      raise exception 'Invalid phone number for %.', v_who;
    end if;

    begin v_year := (p->>'year_of_study')::int; exception when others then v_year := null; end;
    if v_year is null or v_year not between 1 and 5 then
      raise exception 'Year of study must be 1 to 5 for %.', v_who;
    end if;

    begin
      insert into public.hackathon_participants
        (hackathon_id, team_id, role, full_name, registration_number, year_of_study,
         phone, department, college)
      values
        (v_hid, v_team_id, case when v_i = 1 then 'leader' else 'member' end,
         btrim(p->>'full_name'), upper(btrim(p->>'registration_number')), v_year, v_phone,
         btrim(p->>'department'), btrim(p->>'college'));
    exception when unique_violation then
      raise exception 'Registration number % is already registered (or repeated in this form).',
        upper(btrim(p->>'registration_number'));
    end;
  end loop;

  return jsonb_build_object('team_code', v_code, 'team_name', v_name,
                            'whatsapp_link', cfg.whatsapp_link);
end $$;

-- Public: slug + name of the newest hackathon (powers /stack-roulette with no slug).
create or replace function public.hackathon_latest()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('slug', h.slug, 'name', h.name)
  from public.hackathons h order by h.created_at desc limit 1;
$$;

-- Internal: team id for (slug, code, leader reg no), or null. A team proves who
-- it is with its code AND the leader's registration number.
create or replace function public.hackathon_find_team(p_slug text, p_code text, p_leader_reg text)
returns uuid language sql stable security definer set search_path = public as $$
  select tm.id
    from public.hackathons h
    join public.hackathon_teams tm on tm.hackathon_id = h.id
    join public.hackathon_participants pa on pa.team_id = tm.id and pa.role = 'leader'
   where h.slug = p_slug
     and tm.code = btrim(coalesce(p_code, ''))
     and upper(pa.registration_number) = upper(btrim(coalesce(p_leader_reg, '')));
$$;

-- Internal: everything the roulette page needs for one team. The stack is in
-- layer order; `pool` (option names per layer) only feeds the spin animation.
create or replace function public.hackathon_team_view(p_team uuid)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  h public.hackathons;
  t public.hackathon_teams;
  v_stack jsonb;
  v_pool jsonb;
  v_problems jsonb;
  v_problem public.hackathon_problems;
begin
  select * into t from public.hackathon_teams where id = p_team;
  select * into h from public.hackathons where id = t.hackathon_id;

  select coalesce(jsonb_agg(jsonb_build_object('layer', l.layer, 'name', o.name) order by l.ord), '[]'::jsonb)
    into v_stack
    from unnest(h.layers) with ordinality as l(layer, ord)
    join public.hackathon_team_stack s on s.team_id = t.id and s.layer = l.layer
    join public.hackathon_tech_options o on o.id = s.option_id;

  select coalesce(jsonb_object_agg(layer, names), '{}'::jsonb) into v_pool
    from (select o.layer, jsonb_agg(o.name order by o.name) as names
            from public.hackathon_tech_options o
           where o.hackathon_id = h.id and o.active
           group by o.layer) x;

  select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'title', p.title, 'gist', p.gist) order by p.title), '[]'::jsonb)
    into v_problems
    from public.hackathon_problems p where p.hackathon_id = h.id and p.active;

  select * into v_problem from public.hackathon_problems where id = t.problem_id;

  return jsonb_build_object(
    'team_name', t.name, 'team_code', t.code,
    'drawn', t.assigned_at is not null,
    'roulette_open', h.roulette_open,
    'problem_changes', t.problem_changes,
    'stack_rerolls', t.stack_rerolls,
    'max_problem_changes', h.max_problem_changes,
    'max_stack_rerolls', h.max_stack_rerolls,
    'stack', case when t.assigned_at is null then '[]'::jsonb else v_stack end,
    'pool', v_pool,
    'problems', v_problems,
    'problem_id', t.problem_id,
    'problem_title', v_problem.title, 'problem_gist', v_problem.gist);
end $$;

-- Public: a team looks up its state. Same error for "no such team" and "wrong
-- reg number" so it can't be used to probe.
create or replace function public.hackathon_team_result(p_slug text, p_code text, p_leader_reg text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_team uuid := public.hackathon_find_team(p_slug, p_code, p_leader_reg);
begin
  if v_team is null then raise exception 'No team matches that code and registration number.'; end if;
  return public.hackathon_team_view(v_team);
end $$;

-- Internal: (re)deals a team's stack with weighted random picks, one option per
-- layer. Callers hold the hackathon lock. When the team already has a stack the
-- new one is forced to differ (up to 10 tries; impossible if every layer has a
-- single option).
create or replace function public.hackathon_deal_stack(p_team uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  h public.hackathons;
  v_layer text;
  v_u float8;
  v_old text;
  v_new text;
  v_tries int := 0;
begin
  select hh.* into h from public.hackathons hh
    join public.hackathon_teams t on t.hackathon_id = hh.id where t.id = p_team;

  if (select count(distinct layer) from public.hackathon_tech_options
       where hackathon_id = h.id and active and weight > 0 and layer = any (h.layers))
     < cardinality(h.layers) then
    raise exception 'The stack options aren''t set up yet. Ask the organisers.';
  end if;

  select string_agg(layer || ':' || option_id, ',' order by layer) into v_old
    from public.hackathon_team_stack where team_id = p_team;

  loop
    v_tries := v_tries + 1;
    delete from public.hackathon_team_stack where team_id = p_team;
    foreach v_layer in array h.layers loop
      v_u := random();
      insert into public.hackathon_team_stack (team_id, layer, option_id)
      select p_team, v_layer, o.id
        from (select id, sum(weight) over (order by id) as cum, sum(weight) over () as total
                from public.hackathon_tech_options
               where hackathon_id = h.id and layer = v_layer and active and weight > 0) o
       where o.cum > v_u * o.total
       order by o.cum limit 1;
    end loop;
    select string_agg(layer || ':' || option_id, ',' order by layer) into v_new
      from public.hackathon_team_stack where team_id = p_team;
    exit when v_old is null or v_new is distinct from v_old or v_tries >= 10;
  end loop;
end $$;

-- Public: the team picks its problem statement.
--   * First pick: deals the stack.
--   * A different problem later: allowed max_problem_changes times (default 1)
--     and it re-deals the stack too, so a swap is never free.
--   * Same problem again: no-op.
create or replace function public.hackathon_choose_problem(
  p_slug text, p_code text, p_leader_reg text, p_problem_id int)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_team uuid := public.hackathon_find_team(p_slug, p_code, p_leader_reg);
  t public.hackathon_teams;
  h public.hackathons;
begin
  if v_team is null then raise exception 'No team matches that code and registration number.'; end if;

  select * into t from public.hackathon_teams where id = v_team;
  perform pg_advisory_xact_lock(727001, hashtext(t.hackathon_id::text));
  select * into t from public.hackathon_teams where id = v_team;   -- re-read under the lock
  select * into h from public.hackathons where id = t.hackathon_id;

  if not h.roulette_open then raise exception 'Problem selection isn''t open yet.'; end if;
  if not exists (select 1 from public.hackathon_problems
                  where id = p_problem_id and hackathon_id = h.id and active) then
    raise exception 'That problem statement isn''t available.';
  end if;
  if t.assigned_at is not null and t.problem_id = p_problem_id then
    return public.hackathon_team_view(v_team);
  end if;
  if t.assigned_at is not null and t.problem_changes >= h.max_problem_changes then
    raise exception 'You''ve already used your problem change.';
  end if;

  perform public.hackathon_deal_stack(v_team);

  update public.hackathon_teams
     set problem_id = p_problem_id,
         assigned_at = now(),
         problem_changes = problem_changes + case when t.assigned_at is not null then 1 else 0 end
   where id = v_team;

  return public.hackathon_team_view(v_team);
end $$;

-- Public: re-roll only the stack, keeping the problem. Allowed max_stack_rerolls
-- times (default 1), independent of problem changes.
create or replace function public.hackathon_reroll_stack(p_slug text, p_code text, p_leader_reg text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_team uuid := public.hackathon_find_team(p_slug, p_code, p_leader_reg);
  t public.hackathon_teams;
  h public.hackathons;
begin
  if v_team is null then raise exception 'No team matches that code and registration number.'; end if;

  select * into t from public.hackathon_teams where id = v_team;
  perform pg_advisory_xact_lock(727001, hashtext(t.hackathon_id::text));
  select * into t from public.hackathon_teams where id = v_team;
  select * into h from public.hackathons where id = t.hackathon_id;

  if not h.roulette_open then raise exception 'The roulette isn''t open.'; end if;
  if t.assigned_at is null then raise exception 'Pick a problem statement first.'; end if;
  if t.stack_rerolls >= h.max_stack_rerolls then
    raise exception 'You''ve already used your stack re-roll.';
  end if;

  perform public.hackathon_deal_stack(v_team);
  update public.hackathon_teams set stack_rerolls = stack_rerolls + 1 where id = v_team;

  return public.hackathon_team_view(v_team);
end $$;

-- Admin only: random stack + problem for every team not yet drawn.
-- p_redraw = true clears this hackathon's teams first AND rotates draw_seed, so
-- a redraw really produces a different result (the draw is deterministic given
-- seed + team code). Run it from the dashboard: the SQL editor has no logged-in
-- user, so the admin check fails there by design.
create or replace function public.hackathon_run_draw(p_hackathon uuid, p_redraw boolean default false)
returns integer language plpgsql security definer set search_path = public as $$
declare
  v_seed text;
  v_layers text[];
  v_nprob int;
  v_offset int;
  v_count int := 0;
begin
  if not public.hackathon_is_admin() then
    raise exception 'Admins only.' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(727001, hashtext(p_hackathon::text));

  select layers into v_layers from public.hackathons where id = p_hackathon;
  if v_layers is null then raise exception 'Hackathon not found.'; end if;

  select count(*) into v_nprob
    from public.hackathon_problems where hackathon_id = p_hackathon and active;

  if (select count(distinct layer) from public.hackathon_tech_options
       where hackathon_id = p_hackathon and active and weight > 0 and layer = any (v_layers))
     < cardinality(v_layers) then
    raise exception 'Every layer (%) needs at least one active option with weight > 0.',
      array_to_string(v_layers, ', ');
  end if;

  if p_redraw then
    delete from public.hackathon_team_stack
     where team_id in (select id from public.hackathon_teams where hackathon_id = p_hackathon);
    update public.hackathon_teams
       set problem_id = null, assigned_at = null, problem_changes = 0, stack_rerolls = 0
     where hackathon_id = p_hackathon;
    update public.hackathons set draw_seed = gen_random_uuid()::text where id = p_hackathon;
  end if;

  select draw_seed into v_seed from public.hackathons where id = p_hackathon;
  select count(*) into v_offset
    from public.hackathon_teams where hackathon_id = p_hackathon and assigned_at is not null;

  -- weighted pick per (team, layer): hash(seed, code, layer) -> u in [0,1)
  with todo as (
    select t.id, t.code from public.hackathon_teams t
     where t.hackathon_id = p_hackathon and t.assigned_at is null
  ),
  opts as (
    select id, layer,
           sum(weight) over (partition by layer order by id) as cum,
           sum(weight) over (partition by layer) as total
    from public.hackathon_tech_options
    where hackathon_id = p_hackathon and active and weight > 0
  )
  insert into public.hackathon_team_stack (team_id, layer, option_id)
  select todo.id, l.layer,
         (select o.id from opts o
           where o.layer = l.layer
             and o.cum > h.u * o.total
           order by o.cum limit 1)
  from todo
  cross join unnest(v_layers) as l(layer)
  cross join lateral (
    select (('x' || substr(md5(v_seed || todo.code || l.layer), 1, 8))::bit(32)::bigint)
             / 4294967296.0 as u
  ) h
  on conflict (team_id, layer) do update set option_id = excluded.option_id;

  -- problems: shuffled list handed out round-robin, so teams spread evenly
  with todo as (
    select t.id,
           row_number() over (order by md5(v_seed || t.code || 'problem')) as rn
    from public.hackathon_teams t
    where t.hackathon_id = p_hackathon and t.assigned_at is null
  ),
  probs as (
    select id, row_number() over (order by md5(v_seed || 'p' || id::text)) as rk
    from public.hackathon_problems where hackathon_id = p_hackathon and active
  )
  update public.hackathon_teams t
     set problem_id = case when v_nprob = 0 then null else
           (select pr.id from probs pr where pr.rk = ((todo.rn + v_offset - 1) % v_nprob) + 1) end,
         assigned_at = now()
    from todo
   where t.id = todo.id;

  get diagnostics v_count = row_count;
  return v_count;
end $$;

-- Admin only: new hackathon, optionally cloning layers, limits, tech options
-- and problem statements from an earlier one (not teams, WhatsApp link or seed).
create or replace function public.hackathon_create(p_slug text, p_name text, p_copy_from uuid default null)
returns uuid language plpgsql security definer set search_path = public as $$
declare
  v_id uuid;
begin
  if not public.hackathon_is_admin() then
    raise exception 'Admins only.' using errcode = '42501';
  end if;

  if p_copy_from is null then
    insert into public.hackathons (slug, name) values (p_slug, p_name) returning id into v_id;
  else
    insert into public.hackathons (slug, name, layers, max_teams, min_team_size, max_team_size,
                                   max_problem_changes, max_stack_rerolls)
    select p_slug, p_name, h.layers, h.max_teams, h.min_team_size, h.max_team_size,
           h.max_problem_changes, h.max_stack_rerolls
      from public.hackathons h where h.id = p_copy_from
    returning id into v_id;
    if v_id is null then raise exception 'Hackathon to copy from not found.'; end if;

    insert into public.hackathon_tech_options (hackathon_id, layer, name, weight, is_hard, active)
    select v_id, layer, name, weight, is_hard, active
      from public.hackathon_tech_options where hackathon_id = p_copy_from;
    insert into public.hackathon_problems (hackathon_id, title, gist, active)
    select v_id, title, gist, active
      from public.hackathon_problems where hackathon_id = p_copy_from;
  end if;

  return v_id;
exception when unique_violation then
  raise exception 'The slug "%" is already used by another hackathon.', p_slug;
end $$;

