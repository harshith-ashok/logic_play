-- Hackathon portal: reusable, multi-event registration + tech-stack/problem draw.
-- Run once in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Re-runnable: every statement is IF NOT EXISTS / CREATE OR REPLACE / ON CONFLICT.
--
-- Only NEW objects are created (all prefixed `hackathon*`); no existing table,
-- policy or function is touched.
--
-- Model: one row in `hackathons` per event (slug, team-size limits, cap, draw
-- seed, the list of stack "layers"). Everything else hangs off hackathon_id, so
-- running the next hackathon is "create a hackathon" in /admin/hackathons, not
-- another migration.
--
-- Security model:
--   * Public (anon) can call ONLY hackathon_registration_status(slug),
--     hackathon_register_team(slug, ...), hackathon_latest(),
--     hackathon_team_result(slug, code, leader reg no),
--     hackathon_choose_problem(slug, code, leader reg no, problem id) and
--     hackathon_reroll_stack(slug, code, leader reg no). Every table is admin-only via RLS.
--   * Admin = profiles.role = 'core_team' (how the rest of this site decides).
--   * hackathon_run_draw / hackathon_create are admin-only inside the function.
--
-- Order: 1) tables  2) hackathon_is_admin()  3) functions  4) RLS + grants  5) seed

-- =====================================================================
-- 1) Tables
-- =====================================================================

create table if not exists public.hackathons (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique
    check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 60),
  name text not null check (char_length(name) between 2 and 100),
  description text,
  -- the stack categories each team is dealt one option from; the admin UI and
  -- CSV export follow this list, so a design/AI hackathon can use other layers.
  layers text[] not null default array['frontend', 'backend', 'database']
    check (cardinality(layers) between 1 and 6),
  registration_open boolean not null default true,
  roulette_open boolean not null default false,          -- teams may pick their problem + draw a stack
  max_problem_changes int not null default 1 check (max_problem_changes >= 0), -- swaps after the first pick (re-deals the stack)
  max_stack_rerolls int not null default 1 check (max_stack_rerolls >= 0),     -- stack-only re-rolls (problem kept)
  max_teams int not null default 20 check (max_teams between 1 and 900), -- codes are 3 digits
  min_team_size int not null default 2 check (min_team_size >= 1),       -- including leader
  max_team_size int not null default 3,                                  -- including leader
  whatsapp_link text,
  draw_seed text not null default gen_random_uuid()::text,
  created_at timestamptz not null default now(),
  check (min_team_size <= max_team_size and max_team_size <= 10)
);

create table if not exists public.hackathon_tech_options (
  id int generated by default as identity primary key,
  hackathon_id uuid not null references public.hackathons(id) on delete cascade,
  layer text not null,
  name text not null,
  weight int not null default 2 check (weight >= 0),   -- higher = more likely in the draw
  is_hard boolean not null default false,
  active boolean not null default true,
  unique (hackathon_id, layer, name)
);

create table if not exists public.hackathon_problems (
  id int generated by default as identity primary key,
  hackathon_id uuid not null references public.hackathons(id) on delete cascade,
  title text not null,
  gist text,
  active boolean not null default true,
  unique (hackathon_id, title)
);

create table if not exists public.hackathon_teams (
  id uuid primary key default gen_random_uuid(),
  hackathon_id uuid not null references public.hackathons(id) on delete cascade,
  code text not null check (code ~ '^[0-9]{3}$'),
  name text not null,
  problem_id int references public.hackathon_problems(id) on delete set null,
  assigned_at timestamptz,                              -- null = no problem chosen / not drawn yet
  problem_changes int not null default 0,               -- times the team swapped its problem (each re-dealt the stack)
  stack_rerolls int not null default 0,                 -- times the team re-rolled just the stack
  created_at timestamptz not null default now(),
  unique (hackathon_id, code)
);
create unique index if not exists hackathon_teams_name_key
  on public.hackathon_teams (hackathon_id, lower(name));

